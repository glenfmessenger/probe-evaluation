class MissingSource(SystemExit):
    pass


def src(rel: str) -> Path:
    p = REPO / rel
    if not p.exists():
        raise MissingSource(f"gen_tables: MISSING SOURCE {rel}\n"
                            f"  expected at {p}\n"
                            f"  the manuscript cannot be built without it; regenerate it on the branch that produced it "
                            f"or check out the results commit.")
    return p


def srcs(pattern: str, expect: int = None) -> list:
    files = sorted(glob.glob(str(REPO / pattern)))
    if not files:
        raise MissingSource(f"gen_tables: MISSING SOURCE {pattern} (no files matched)")
    if expect is not None and len(files) != expect:
        raise MissingSource(f"gen_tables: SOURCE COUNT MISMATCH for {pattern}: found {len(files)}, expected {expect}")
    return files


def load(rel):
    return json.load(open(src(rel)))


def by_model(pattern, expect=7):
    out = {}
    for f in srcs(pattern, expect):
        d = json.load(open(f))
        out[d["model"]] = d
    return out


def f3(x):
    return "--" if x is None else f"{x:.3f}"


def f2(x):
    return "--" if x is None else f"{x:.2f}"


def booktabs(body: str) -> str:
    """Rewrite the \\hline rules of a single tabular into booktabs rules: first -> \\toprule, last -> \\bottomrule,
    any in between -> \\midrule. Applied centrally in emit() so no generator has to remember to do it."""
    lines = body.split("\n")
    idx = [i for i, l in enumerate(lines) if l.strip() == r"\hline"]
    for n, i in enumerate(idx):
        lines[i] = r"\toprule" if n == 0 else (r"\bottomrule" if n == len(idx) - 1 else r"\midrule")
    return "\n".join(lines)


def emit(name: str, body: str, sources: list, size: str = None, colsep: float = None, wide: bool = False):
    """`size` and `colsep` shrink a table that overflows the column. The values here were set from the overfull-hbox
    warnings of an actual compile (`make smoke`), not guessed: every table in this file fits without a warning."""
    hdr = ("% GENERATED by paper/tools/gen_tables.py -- do not edit by hand.\n"
           f"% sources: {', '.join(sources)}\n")
    body = booktabs(body)
    if wide:
        # promote to a two-column float, rewriting BOTH tags so they cannot disagree
        body = body.replace(r"\begin{table}[", r"\begin{table*}[").replace(r"\end{table}", r"\end{table*}")
    if size or colsep:
        inject = ""
        if colsep is not None:
            inject += rf"\setlength{{\tabcolsep}}{{{colsep}pt}}" + "\n"
        if size:
            inject += "\\" + size + "\n"
        body = body.replace(r"\centering" + "\n", r"\centering" + "\n" + inject, 1)
    (TABLES / name).write_text(hdr + body)
    return name


