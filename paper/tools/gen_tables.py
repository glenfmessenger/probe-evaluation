"""Generate every LaTeX table in the manuscript from the committed, provenance-stamped results files.

PAPER_BRIEF framing rule 3: no untraced numbers. Nothing in the manuscript is typed by hand; each table is emitted here
from a results JSON, and **the build fails if any declared source is missing** rather than silently producing a
manuscript with a stale or absent table.

Each generator declares its sources in SOURCES. `main()` resolves every source first, so a missing file aborts before
anything is written — a partially regenerated tables/ directory is worse than none. Every emitted file carries a header
comment naming its generator and sources, and `tables/_provenance.tex` records the git commit and the sha256 of each
source so the manuscript can state what it was built from.

  python paper/tools/gen_tables.py           # regenerate all
  python paper/tools/gen_tables.py --check    # verify sources exist and tables are up to date; write nothing
"""
