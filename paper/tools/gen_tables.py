def sha256(p: Path) -> str:
    h = hashlib.sha256()
    h.update(p.read_bytes())
    return h.hexdigest()


def write_provenance(written):
    # Record the commit the RESULTS are at, not repository HEAD. HEAD changes every time this stamp is committed,
    # which never settles; the last commit touching results/ is both stable and the thing the number actually means.
    # "dirty" likewise asks whether results/ has uncommitted changes, not whether any file anywhere does.
    try:
        commit = subprocess.check_output(
            ["git", "-C", str(REPO), "log", "-1", "--format=%H", "--", "results"], text=True).strip()
        dirty = bool(subprocess.check_output(
            ["git", "-C", str(REPO), "status", "--porcelain", "--", "results"], text=True).strip())
        if not commit:
            commit, dirty = "unknown", True
    except Exception:
        commit, dirty = "unknown", True
    lines = [r"% GENERATED by paper/tools/gen_tables.py -- do not edit by hand.",
             rf"\newcommand{{\resultscommit}}{{{commit[:12]}{'+dirty' if dirty else ''}}}",
             rf"\newcommand{{\ntablesgenerated}}{{{len(written)}}}"]
    files = []
    for pat in SOURCES:
        for f in sorted(glob.glob(str(REPO / pat))):
            rel = Path(f).relative_to(REPO)
            files.append(f"% {rel} {sha256(Path(f))[:16]}")
    (TABLES / "_provenance.tex").write_text("\n".join(lines + files) + "\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="verify sources and freshness, write nothing")
    a = ap.parse_args(argv)
    # resolve every declared source before writing anything
    for pat in SOURCES:
        if "*" in pat:
            srcs(pat)
        else:
            src(pat)
    if a.check:
        missing = [g.__name__ for g in GENERATORS
                   if not (TABLES / f"{g.__name__.replace('tab_', 'tab_')}.tex").exists()]
        stale = [n for n in (TABLES / "_provenance.tex",) if not n.exists()]
        if missing or stale:
            raise SystemExit(f"gen_tables --check: tables not generated: {missing or ''} {stale or ''}")
        print(f"gen_tables --check: all {len(SOURCES)} source patterns present, "
              f"{len(list(TABLES.glob('tab_*.tex')))} tables on disk")
        return 0
    TABLES.mkdir(parents=True, exist_ok=True)
    written = []
    for g in GENERATORS:
        written.append(g())
        print(f"  wrote paper/tables/{written[-1]}")
    write_provenance(written)
    print(f"gen_tables: {len(written)} tables + _provenance.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
